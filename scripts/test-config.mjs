// The Worker config every LOCAL test server uses: wrangler.jsonc as it is, minus the Workers AI
// binding. With `ai` in the config, `wrangler dev` needs a Cloudflare login and every Lens call
// would spend the account's real neurons; tests send Lens to a fake model (LENS_FAKE_AI) instead.
// Written next to wrangler.jsonc (its paths are relative to it) and gitignored.
// `node scripts/test-config.mjs` prints the path (the phone workflow uses that).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

export function testConfig() {
  const ts = createRequire(import.meta.url)('typescript');
  const { config, error } = ts.parseConfigFileTextToJson('wrangler.jsonc', readFileSync(`${ROOT}wrangler.jsonc`, 'utf8'));
  if (error || !config) throw new Error(`wrangler.jsonc did not parse: ${error?.messageText ?? 'empty'}`);
  delete config.ai;
  const path = `${ROOT}wrangler.test.jsonc`;
  writeFileSync(path, `// Generated by scripts/test-config.mjs from wrangler.jsonc, without the AI binding. Do not edit.\n${JSON.stringify(config, null, 2)}\n`);
  return path;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) console.log(testConfig());
